def _apply_price(obj, price: str):
    if isinstance(obj, str):
        return obj.replace(P, price)
    if isinstance(obj, list):
        return [_apply_price(x, price) for x in obj]
    if isinstance(obj, tuple):
        return tuple(_apply_price(x, price) for x in obj)
    return obj


